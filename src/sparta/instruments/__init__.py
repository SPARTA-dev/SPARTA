"""Per-instrument spectrum loaders and their metadata.

Each instrument module exports ``PRODUCTS``, a tuple of
`~sparta.instruments.base.Product`; ``REGISTRY`` maps every product's survey
key to it, and `get` looks one up::

    from sparta import instruments
    spec = instruments.get("HARPS").load(path, min_wv=4990, max_wv=5090)

Wavelengths are returned in Angstrom, velocities in km/s, times in days.
``docs/instruments.md`` is generated from the registry by
``python -m sparta.instruments`` (see `render_markdown`).
"""
from sparta.instruments import (apogee, coralie, elodie, feros, harps, lamost, nres, pepsi,
                                srg, tres, uves)
from sparta.instruments.base import Instrument, LoadedSpectrum, Product, Recommended

__all__ = ["REGISTRY", "get", "render_markdown",
           "Instrument", "LoadedSpectrum", "Product", "Recommended"]

MODULES = (harps, nres, apogee, coralie, elodie, feros, lamost, pepsi, srg, tres, uves)


def _build_registry(modules):
    registry = {}
    for module in modules:
        for product in module.PRODUCTS:
            if product.survey in registry:
                raise ValueError(f"duplicate survey key {product.survey!r} "
                                 f"(in {module.__name__})")
            registry[product.survey] = product
    return registry


REGISTRY = _build_registry(MODULES)


def get(survey):
    '''
    The product registered under a survey key.

    Parameters
    ----------
    survey : str
        Registry key, e.g. 'HARPS'.

    Returns
    -------
    Product

    Raises
    ------
    ValueError
        If ``survey`` is not registered; the message lists the known keys.
    '''
    try:
        return REGISTRY[survey]
    except KeyError:
        raise ValueError(f"unknown survey {survey!r}; known surveys: "
                         f"{', '.join(sorted(REGISTRY))}") from None


def _cell(value):
    return "—" if value is None else str(value)


def _product_markdown(product):
    loader = f"{product.load.__module__}.{product.load.__qualname__}"
    lines = [f"### `{product.survey}`" + ("" if product.verified else " (unverified)"),
             "",
             product.description,
             "",
             f"- Loader: `{loader}`",
             f"- Grid: {product.grid}" + (" (resampled by the archive pipeline)"
                                          if product.resampled else ""),
             f"- Orders returned: {'all' if product.multi_order else 'one'}",
             f"- Wavelength frame: {_cell(product.wavelength_frame)}; "
             f"SPECSYS: {_cell(product.specsys)}; time: {product.time_system}"]
    rec = product.recommended
    if rec == Recommended():
        return lines + ["- Recommended settings: none yet"]
    if rec.dv_kms is not None:
        lines.append(f"- Recommended CCF step: {rec.dv_kms:g} km/s")
    if rec.window_A is not None:
        lines.append(f"- Recommended window: {rec.window_A[0]:g}–{rec.window_A[1]:g} Å")
    if rec.preprocess:
        lines.append("- Recommended preprocessing: `SpecPreProccess("
                     + ", ".join(f"{k}={v!r}" for k, v in rec.preprocess.items()) + ")`")
    if rec.drop_orders:
        lines.append(f"- Orders to drop: {_ranges(rec.drop_orders)}")
    return lines


def _ranges(indices):
    """Compact '0-9, 50-66' form of a sorted tuple of integers."""
    runs, start = [], None
    for i, k in enumerate(indices):
        if start is None:
            start = k
        if i + 1 == len(indices) or indices[i + 1] != k + 1:
            runs.append(f"{start}" if start == k else f"{start}–{k}")
            start = None
    return ", ".join(runs)


def render_markdown():
    '''
    Markdown reference of every registered product, grouped by instrument.

    Returns
    -------
    str
        The content of ``docs/instruments.md``.
    '''
    lines = ["# SPARTA instruments",
             "",
             "<!-- Generated by `python -m sparta.instruments` from "
             "sparta.instruments.REGISTRY; do not edit by hand. -->",
             "",
             "Pass the survey key to `Observations(survey=...)` or "
             "`sparta.instruments.get(...)`. Unverified loaders have not been checked "
             "against archive files and warn (UserWarning) on every load.",
             "",
             "| Survey key | Instrument | Verified | Orders | Grid | λ frame | SPECSYS | Time |",
             "|---|---|---|---|---|---|---|---|"]
    for p in REGISTRY.values():
        lines.append(f"| `{p.survey}` | {p.instrument.name} | {'yes' if p.verified else 'no'} | "
                     f"{'all' if p.multi_order else 'one'} | "
                     f"{'resampled' if p.resampled else 'native'} | "
                     f"{_cell(p.wavelength_frame)} | {_cell(p.specsys)} | {p.time_system} |")

    by_instrument = {}
    for p in REGISTRY.values():
        by_instrument.setdefault(p.instrument, []).append(p)
    for instrument, products in by_instrument.items():
        lines += ["", f"## {instrument.name}", "",
                  "- Resolving power: " + ("—" if instrument.resolving_power is None
                                           else f"{instrument.resolving_power:,.0f}"),
                  "- Native step: " + ("—" if instrument.native_step_kms is None
                                       else f"{instrument.native_step_kms:g} km/s per pixel")]
        if instrument.notes:
            lines.append(f"- Notes: {instrument.notes}")
        if instrument.references:
            lines.append("- References: " + ", ".join(f"<{r}>" for r in instrument.references))
        for p in products:
            lines += [""] + _product_markdown(p)
    return "\n".join(lines) + "\n"
